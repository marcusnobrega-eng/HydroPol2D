function [surface_depth_m, media_saturation, gravel_fraction, row] = ...
    hp2d_green_infrastructure_outputs(G, S, time_min)
%HP2D_GREEN_INFRASTRUCTURE_OUTPUTS Map and facility outputs of the GI stores
%   (HydroPol2D-Python _green_infrastructure_maps and the facility history).
%   Maps (NaN outside GI cells; where facilities share a cell the last one is
%   shown, as in Python): ponded depth [m], media water / media pore volume
%   [-] and gravel water / gravel pore volume [-].
%   row: one table row per facility at time_min [min] with the storages [m3],
%   the rates of the last step [m3/s] and the cumulative volumes [m3].
surface_depth_m = nan(G.shape);
media_saturation = nan(G.shape);
gravel_fraction = nan(G.shape);
media_capacity = G.area_m2 .* G.media_depth_m .* G.media_porosity;
gravel_capacity = G.area_m2 .* G.gravel_depth_m .* G.gravel_void_fraction;
surface_depth_m(G.cell_index) = S.surface_m3 ./ G.area_m2;
media_saturation(G.cell_index) = S.media_m3 ./ max(media_capacity, 1e-12);
gravel_fraction(G.cell_index) = S.gravel_m3 ./ max(gravel_capacity, 1e-12);
if nargout < 4
    return
end
f = G.facility_index;
n = G.facility_count;
sum_f = @(v) accumarray(f, v(:), [n 1]);
dt = max(S.step_dt_s, eps);
row = table(repmat(time_min, n, 1), string(G.facility_identifiers(:)), ...
    sum_f(S.surface_m3), sum_f(S.media_m3), sum_f(S.gravel_m3), ...
    sum_f(S.step_capture_m3)/dt, sum_f(S.step_infiltration_m3)/dt, ...
    sum_f(S.step_overflow_m3)/dt, sum_f(S.step_native_exfiltration_m3)/dt, ...
    sum_f(S.step_et_m3)/dt, sum_f(S.step_underdrain_m3)/dt, ...
    sum_f(S.cumulative_rain_m3), sum_f(S.cumulative_capture_m3), ...
    sum_f(S.cumulative_overflow_m3), sum_f(S.cumulative_native_exfiltration_m3), ...
    sum_f(S.cumulative_et_m3), sum_f(S.cumulative_underdrain_m3), ...
    'VariableNames', {'time_min', 'facility', 'surface_storage_m3', 'media_storage_m3', ...
    'gravel_storage_m3', 'capture_m3_s', 'media_infiltration_m3_s', 'overflow_m3_s', ...
    'native_exfiltration_m3_s', 'evapotranspiration_m3_s', 'underdrain_m3_s', ...
    'cumulative_rain_m3', 'cumulative_capture_m3', 'cumulative_overflow_m3', ...
    'cumulative_native_exfiltration_m3', 'cumulative_evapotranspiration_m3', ...
    'cumulative_underdrain_m3'});
end
