function [volume_m3,discharge_m3_s,mass_residual_m3] = ...
        hp2d_river_groundwater_exchange_step(kbed_m_s,thickness_m,area_m2, ...
        groundwater_head_m,river_stage_m,groundwater_volume_m3, ...
        river_volume_m3,groundwater_storage_area_m2,river_storage_area_m2, ...
        dt_s,active)
%HP2D_RIVER_GROUNDWATER_EXCHANGE_STEP Exact storage-limited two-store exchange.
assert(isfinite(thickness_m) && thickness_m>0 && dt_s>0, ...
    'HydroPol2D:InvalidRiverbedParameters', ...
    'Riverbed thickness and exchange timestep must be positive.');
conductance=max(kbed_m_s,0)./thickness_m.*max(area_m2,0);
inverse_storage=1./max(groundwater_storage_area_m2,eps)+ ...
    1./max(river_storage_area_m2,eps);
relaxation=conductance.*inverse_storage;
requested=(groundwater_head_m-river_stage_m).* ...
    (-expm1(-relaxation.*dt_s))./max(inverse_storage,realmin);
requested(~active)=0;
volume_m3=requested;
to_river=volume_m3>=0;
volume_m3(to_river)=min(volume_m3(to_river),max(groundwater_volume_m3(to_river),0));
to_groundwater=volume_m3<0;
volume_m3(to_groundwater)=-min(-volume_m3(to_groundwater),max(river_volume_m3(to_groundwater),0));
discharge_m3_s=volume_m3./dt_s;
mass_residual_m3=volume_m3-volume_m3;
end
