function Summary=run_voronoi_adaptive_groundwater_validation(mesh_file)
%RUN_VORONOI_ADAPTIVE_GROUNDWATER_VALIDATION Error control and closed mass.
root=fullfile(fileparts(mfilename('fullpath')),'..','..');
addpath(fullfile(root,'HydroPol2D_Functions'));
mesh=HydroPol2D_Read_UGRID(mesh_file);
n=mesh.n_cells;

head=mesh.surface_bed-1;
head(round(n/2))=mesh.surface_bed(round(n/2))-0.1;
bottom=mesh.surface_bed-3;
groundwater=struct('enabled',true,'head',head,'bottom',bottom, ...
    'hydraulic_conductivity',1e-2*ones(n,1), ...
    'specific_yield',0.2*ones(n,1),'pending_exchange_m3',zeros(n,1), ...
    'elapsed_s',0,'last_river_exchange_rate_m_s',zeros(n,1), ...
    'last_seepage_rate_m_s',zeros(n,1), ...
    'cumulative_river_exchange_m',zeros(n,1), ...
    'cumulative_seepage_m',zeros(n,1));
groundwater.storage=groundwater.specific_yield.* ...
    (groundwater.head-groundwater.bottom).*mesh.cell_area(:);
surface=zeros(n,1);
channel=zeros(mesh.channel.n_nodes,1);
initial_storage=sum(groundwater.storage);
config=struct('groundwater_lateral_flow',true,'groundwater_courant',0.25, ...
    'groundwater_relative_tolerance',1e-8,'groundwater_head_tolerance_m',1e-9, ...
    'min_dt_s',0.001,'river_groundwater_exchange',false, ...
    'riverbed_thickness_m',0.5);

[surface,channel,groundwater,diagnostics]=Voronoi_Groundwater_Advance( ...
    mesh,surface,channel,groundwater,600,config);
mass_residual=sum(groundwater.storage)+sum(surface)+sum(channel)-initial_storage;
passed=abs(mass_residual)<1e-8 && diagnostics.substep_count>0 && ...
    diagnostics.rejected_steps>0 && diagnostics.suggested_dt_s>0;
Summary=table(mass_residual,diagnostics.substep_count,diagnostics.rejected_steps, ...
    diagnostics.suggested_dt_s,passed, ...
    'VariableNames',{'mass_residual_m3','accepted_steps','rejected_steps', ...
    'suggested_dt_s','passed'});
disp(Summary);
assert(passed,'HydroPol2D:VoronoiAdaptiveGroundwater', ...
    'Voronoi adaptive groundwater validation failed.');
end
