function Summary = run_current_physics_flux_fixture(output_csv)
%RUN_CURRENT_PHYSICS_FLUX_FIXTURE Shared synthetic fixture for Python/MATLAB parity.
arguments
    output_csv (1,:) char = fullfile(tempdir,'hydropol2d-current-physics-flux-fixture.csv')
end
root=fullfile(fileparts(mfilename('fullpath')),'..','..');
addpath(fullfile(root,'HydroPol2D_Functions'));

[volume,discharge,residual]=hp2d_river_groundwater_exchange_step( ...
    [1e-6;2e-6],0.5,[100;200],[2;0],[1;1],[100;100],[100;0.05], ...
    [20;20],[100;100],100,true(2,1));
capillary=hp2d_vg_mualem_capillary_transfer( ...
    [12;7.6]./1000./3600,[1.6;1.6],[1.37;1.37],[0.5;0.5], ...
    [0;13.7],3.3,[0.3;0.3],[0;0],[1;1],3600);

assert(max(abs(residual))<1e-12,'HydroPol2D:ExchangeMass','Exchange mass did not close.');
expected_gaining=(1-exp(-0.0012))/0.06;
assert(abs(volume(1)-expected_gaining)<1e-12 && abs(volume(2)+0.05)<1e-12, ...
    'HydroPol2D:ExchangeFixture','Storage-limited exchange fixture failed.');
assert(abs(capillary(1)-0.012)<1e-12 && capillary(2)<1e-7, ...
    'HydroPol2D:CapillaryFixture','VG-Mualem capillary fixture failed.');

Summary=table(volume(1),volume(2),discharge(1),discharge(2), ...
    capillary(1),capillary(2),max(abs(residual)), ...
    'VariableNames',{'gaining_exchange_m3','losing_exchange_m3', ...
    'gaining_discharge_m3_s','losing_discharge_m3_s', ...
    'shallow_capillary_m','deep_capillary_m','mass_residual_m3'});
writetable(Summary,output_csv);
disp(Summary);
end
